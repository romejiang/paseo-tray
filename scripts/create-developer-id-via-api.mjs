#!/usr/bin/env node
/**
 * Create a Developer ID Application certificate through the App Store Connect API.
 *
 * Required environment:
 *   ASC_ISSUER_ID       Issuer ID from App Store Connect -> Users and Access -> Integrations
 *   ASC_KEY_ID          Key ID of an App Store Connect API key
 *   ASC_PRIVATE_KEY_PATH Path to the App Store Connect API .p8 (NOT an APNs key)
 *
 * Optional:
 *   ASC_CERT_TYPE       DEVELOPER_ID_APPLICATION_G2 (default) or DEVELOPER_ID_APPLICATION
 *   PASEOTRAY_SIGN_DIR  default ~/.paseo-tray-signing
 *
 * This script reuses developerID.csr / developerID.key generated by
 * scripts/create-developer-id-csr.sh. The private key never leaves this machine.
 */
import { execFileSync } from "node:child_process";
import { createPrivateKey, sign } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const dryRun = process.argv.includes("--dry-run");
const issuerId = process.env.ASC_ISSUER_ID?.trim();
const keyId = process.env.ASC_KEY_ID?.trim();
const keyPathRaw = process.env.ASC_PRIVATE_KEY_PATH?.trim();
const certType = process.env.ASC_CERT_TYPE?.trim() || "DEVELOPER_ID_APPLICATION_G2";
const signDir = path.resolve(
  (process.env.PASEOTRAY_SIGN_DIR || path.join(homedir(), ".paseo-tray-signing")).replace(
    /^~/,
    homedir(),
  ),
);
const csrPath = path.join(signDir, "developerID.csr");
const keyPath = path.join(signDir, "developerID.key");
const cerPath = path.join(signDir, "developerID.cer");

function base64url(value) {
  return Buffer.from(value)
    .toString("base64")
    .replace(/=/g, "")
    .replace(/\+/g, "-")
    .replace(/\//g, "_");
}

function usage(message) {
  console.error(`Error: ${message}`);
  console.error(
    "Required: ASC_ISSUER_ID, ASC_KEY_ID, ASC_PRIVATE_KEY_PATH (App Store Connect API key, not APNs).",
  );
  process.exit(1);
}

if (!issuerId) usage("ASC_ISSUER_ID is missing");
if (!keyId) usage("ASC_KEY_ID is missing");
if (!keyPathRaw) usage("ASC_PRIVATE_KEY_PATH is missing");

const apiKeyPath = path.resolve(keyPathRaw.replace(/^~/, homedir()));
const csr = await readFile(csrPath, "utf8");
const privateKey = createPrivateKey(await readFile(apiKeyPath, "utf8"));

const now = Math.floor(Date.now() / 1000);
const header = { alg: "ES256", kid: keyId, typ: "JWT" };
const payload = {
  iss: issuerId,
  iat: now,
  exp: now + 20 * 60,
  aud: "appstoreconnect-v1",
};
const signingInput = `${base64url(JSON.stringify(header))}.${base64url(JSON.stringify(payload))}`;
const signature = sign("sha256", Buffer.from(signingInput), {
  key: privateKey,
  dsaEncoding: "ieee-p1363",
});
const jwt = `${signingInput}.${base64url(signature)}`;

if (dryRun) {
  console.log("Dry run OK");
  console.log(`  issuer: ${issuerId}`);
  console.log(`  keyId: ${keyId}`);
  console.log(`  certType: ${certType}`);
  console.log(`  csr: ${csrPath} (${csr.length} bytes)`);
  console.log(`  private key: ${keyPath} (not printed)`);
  process.exit(0);
}

const response = await fetch("https://api.appstoreconnect.apple.com/v1/certificates", {
  method: "POST",
  headers: {
    Authorization: `Bearer ${jwt}`,
    "Content-Type": "application/json",
    Accept: "application/json",
  },
  body: JSON.stringify({
    data: {
      type: "certificates",
      attributes: {
        certificateType: certType,
        csrContent: csr,
      },
    },
  }),
});

const text = await response.text();
let body;
try {
  body = JSON.parse(text);
} catch {
  body = null;
}

if (!response.ok) {
  console.error(`App Store Connect API returned ${response.status}`);
  if (body?.errors) {
    for (const error of body.errors) {
      console.error(`  ${error.code ?? "ERROR"}: ${error.title ?? ""} ${error.detail ?? ""}`);
    }
  } else {
    console.error(text.slice(0, 1000));
  }
  if (response.status === 401) {
    console.error(
      "This usually means the .p8 is not an App Store Connect API key (an APNs key cannot be used here), or the issuer/key ID is wrong.",
    );
  }
  if (response.status === 403) {
    console.error(
      "The API key role must be Admin (or Account Holder) to manage certificates. Enable API access as the Account Holder and create an Admin key.",
    );
  }
  process.exit(1);
}

const certificateContent = body?.data?.attributes?.certificateContent;
if (!certificateContent) {
  console.error("API response did not contain certificateContent.");
  console.error(JSON.stringify(body, null, 2).slice(0, 2000));
  process.exit(1);
}

await writeFile(cerPath, Buffer.from(certificateContent, "base64"));
console.log(`Certificate written: ${cerPath}`);
console.log(`Certificate ID: ${body.data.id}`);
console.log("Installing certificate with scripts/install-developer-id.sh...");
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
execFileSync("bash", [path.join(scriptDir, "install-developer-id.sh"), cerPath], {
  stdio: "inherit",
});
